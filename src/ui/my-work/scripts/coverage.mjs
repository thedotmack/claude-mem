// Spec coverage: every "ui" requirement must be tagged by at least one `ids={[...]}` prop in src (<Req> or a component that passes them to <Req>).
// Writes COVERAGE.md and exits 1 when a ui requirement is untagged.
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'
import { REQUIREMENTS as requirements } from '../src/spec/requirements.ts'

const root = fileURLToPath(new URL('..', import.meta.url))

const sourceFiles = []
const walk = (dir) => {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name)
    if (statSync(path).isDirectory()) { if (!['ui', 'ai-elements', 'spec'].includes(name)) walk(path) }
    else if (/\.tsx?$/.test(name)) sourceFiles.push(path)
  }
}
walk(join(root, 'src'))

const tagsById = new Map(requirements.map((requirement) => [requirement.id, []]))
for (const file of sourceFiles) {
  const source = readFileSync(file, 'utf8')
  for (const match of source.matchAll(/\bids=\{\[([^\]]+)\]\}/g)) {
    const line = source.slice(0, match.index).split('\n').length
    for (const [, id] of match[1].matchAll(/'([^']+)'/g)) {
      if (!tagsById.has(id)) throw new Error(`${relative(root, file)}:${line} tags unknown requirement ${id}`)
      tagsById.get(id).push(`${relative(root, file)}:${line}`)
    }
  }
}

const uiRequirements = requirements.filter((requirement) => requirement.kind === 'ui')
const missing = uiRequirements.filter((requirement) => tagsById.get(requirement.id).length === 0)
const rows = requirements.map((requirement) => {
  const tags = tagsById.get(requirement.id)
  const covered = requirement.kind !== 'ui' ? `n/a (${requirement.kind})` : tags.length ? 'yes' : '**MISSING**'
  const where = tags.length ? tags.map((tag) => `\`${tag}\``).join(', ') : requirement.wireframe ?? ''
  return `| ${requirement.id} | §${requirement.section} | ${covered} | ${requirement.text.replace(/\|/g, '\\|')} | ${where} |`
})
writeFileSync(join(root, 'COVERAGE.md'), `# Spec coverage

Generated by \`npm run coverage\` from \`src/spec/requirements.ts\` and the \`<Req>\` tags in \`src\`.

**${uiRequirements.length - missing.length} of ${uiRequirements.length} UI requirements covered.** ${requirements.length - uiRequirements.length} backend or process requirements are listed for completeness.

| ID | Spec | Covered | Requirement | Where |
| --- | --- | --- | --- | --- |
${rows.join('\n')}
`)
console.log(`${uiRequirements.length - missing.length}/${uiRequirements.length} UI requirements covered`)
if (missing.length) {
  console.log('Missing:', missing.map((requirement) => requirement.id).join(', '))
  process.exit(1)
}
